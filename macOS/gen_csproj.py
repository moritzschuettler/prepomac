#!/usr/bin/env python3
"""Generates the macOS SDK project of a shared PrePoMax library from its .NET Framework project.

The compile items are taken from the original project so that both builds compile the same sources. Files that are
Windows specific are excluded and replaced by files in the Mac folder of the macOS project.
Usage: gen_csproj.py <original.csproj> <macOS project dir> <assembly name> [--exclude file ...] [--ref project ...]
       [--pkg name=version ...] [--unsafe]
"""
import argparse, os, re, sys

parser = argparse.ArgumentParser()
parser.add_argument("original")
parser.add_argument("outdir")
parser.add_argument("assembly")
parser.add_argument("--exclude", nargs="*", default=[])
parser.add_argument("--exclude-file")
parser.add_argument("--ref", nargs="*", default=[])
parser.add_argument("--pkg", nargs="*", default=[])
parser.add_argument("--unsafe", action="store_true")
args = parser.parse_args()

text = open(args.original, encoding="utf-8-sig").read()
folder = os.path.basename(os.path.dirname(os.path.abspath(args.original)))
items = re.findall(r'<Compile Include="([^"]+)"', text)
if args.exclude_file:
    args.exclude += [l.strip() for l in open(args.exclude_file) if l.strip() and not l.startswith("#")]
exclude = {e.replace("/", "\\") for e in args.exclude}
items = [i for i in items if i not in exclude and not i.startswith("Properties\\AssemblyInfo")]

lines = ['<Project Sdk="Microsoft.NET.Sdk">',
         '  <!-- Generated by macOS/gen_csproj.py from ' + folder + '/' + os.path.basename(args.original) + ' -->',
         '  <PropertyGroup>',
         '    <AssemblyName>%s</AssemblyName>' % args.assembly,
         '    <RootNamespace>%s</RootNamespace>' % args.assembly]
if args.unsafe:
    lines.append('    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>')
output_type = (re.findall(r'<OutputType>([^<]+)</OutputType>', text) or ['Library'])[0]
if output_type in ('WinExe', 'Exe'):
    lines.append('    <OutputType>Exe</OutputType>')
lines += ['  </PropertyGroup>', '  <ItemGroup>']
for i in items:
    lines.append('    <Compile Include="$(RepoRoot)%s\\%s" />' % (folder, i))
lines.append('    <Compile Include="Mac\\**\\*.cs" />')
# Resources of the forms: the manifest name of WinForms is the namespace and the class of the file they belong to
root = os.path.dirname(os.path.abspath(args.original))
rootns = (re.findall(r'<RootNamespace>([^<]+)</RootNamespace>', text) or [args.assembly])[0]
for res in re.findall(r'<EmbeddedResource Include="([^"]+\.resx)"', text):
    path = os.path.join(root, res.replace('\\', '/'))
    if not os.path.exists(path) or res.replace('/', '\\') in exclude:
        continue
    base = os.path.splitext(res.replace('\\', '/'))[0]
    cs = os.path.join(root, base + '.cs')
    logical = None
    if os.path.exists(cs):
        src = open(cs, encoding='utf-8-sig', errors='ignore').read()
        ns = re.search(r'^\s*namespace\s+([\w.]+)', src, re.M)
        # The class named like the file, or the first class of the file
        fname = os.path.basename(base)
        cls = re.search(r'\b(?:class|struct)\s+(' + re.escape(fname) + r')\b', src) or \
              re.search(r'\b(?:class|struct)\s+(\w+)', src)
        if cls:
            logical = (ns.group(1) + '.' if ns else '') + cls.group(1)
    if logical is None:
        logical = rootns + '.' + base.replace('/', '.')
    if base.replace('/', '.').endswith('Properties.Resources'):
        logical = rootns + '.Properties.Resources'
    lines.append('    <EmbeddedResource Include="$(RepoRoot)%s\\%s" LogicalName="%s.resources" />' % (folder, res, logical))
lines.append('  </ItemGroup>')
if args.exclude_file:
    lines.append('  <!-- The files listed in ' + os.path.basename(args.exclude_file) + ' are replaced on macOS -->')
elif args.exclude:
    lines.append('  <!-- Replaced on macOS: ' + ', '.join(sorted(exclude)) + ' -->')
lines.append('  <ItemGroup>')
for r in args.ref:
    lines.append('    <ProjectReference Include="..\\%s\\%s.csproj" />' % (r, r))
for p in args.pkg:
    name, version = p.split("=")
    lines.append('    <PackageReference Include="%s" Version="%s" />' % (name, version))
lines += ['  </ItemGroup>', '</Project>', '']
os.makedirs(os.path.join(args.outdir, "Mac"), exist_ok=True)
open(os.path.join(args.outdir, args.assembly + ".csproj"), "w").write("\n".join(lines))
print("%s: %d files" % (args.assembly, len(items)))
